# It focuses on the if-else statement, which is a fundamental control structure in programming.
# The if-else statement allows you to execute different blocks of code based on certain conditions.

score = 78
if score >= 90:
    print("Grade: A")
elif score >= 75:
    print("Grade: B")
else:
    print("Grade: C")

# Shorthand if-else statement
age = 18
status = "Adult" if age >= 18 else "Minor"
print(status)  